/*
 * term_detect.c: определение внешней подтяжки на линии SCK.
 *
 * ADC_SCK (PB1) выведен не только на ЦАП, но и на служебный разъём J2
 * (контакт 4), поэтому внешнее оборудование может притянуть эту линию
 * к земле. Проверка: линия поднимается выходом, затем переводится во вход
 * с подтяжкой, и через ~25 мс читается фактический уровень.
 */
#include "lc1.h"

uint8_t sck_pulldown_detect(void)
{
    uint8_t pin;

    PORTB = 0x01;
    DDRB  = 0x97;

    PORTB |= (1 << P_ADC_SCK);
    delay_ms(50);

    DDRB &= (uint8_t)~(1 << P_ADC_SCK);
    delay_ms(50);

    pin = PINB;

    PORTB &= (uint8_t)~(1 << P_ADC_SCK);
    DDRB |= (1 << P_ADC_SCK);

    /* инвертированный бит 1, т.е. 1 = линия притянута к земле снаружи. */
    return (uint8_t)(~(pin >> 1)) & 1;
}
