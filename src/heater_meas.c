/*
 * heater_meas.c: измерение сопротивления нагревателя и диагностика
 *                 силовой части.
 *
 * Сопротивление нагревателя считается как Rheat = Ubat / Iheat и хранится
 * В МИЛЛИОМАХ. Единицы доказываются тремя порогами, которые совпадают с
 * опубликованной таблицей LC-1 (документация к версии 1.10F):
 *   g_rheat_min_mohm  = 2000 / 1800 / 1600  -> 2.0 / 1.8 / 1.6 Ohm
 *   константа 30001                          -> максимум 30 Ohm
 *   g_rheat_target_mohm = 9100 / 6000 / 7500 -> 9.1 / 6.0 / 7.5 Ohm
 *
 * Паспорт Bosch на LSU 4.9 (Y 258 E00 015e от 14.06.2005, п.1.5) единицы
 * подтверждает независимо:
 *   номинальное напряжение нагревателя            7.5 В
 *   мощность в равновесии на воздухе              ~7.5 Вт  -> 7.5 Ом
 *   холодное сопротивление при комнатной t        3.2 Ом
 *   минимальное холодное при -40 degC               1.8 Ом
 * То есть уставка 7500 - это ровно паспортная рабочая точка LSU 4.9, а
 * порог 1800 совпадает с паспортным минимумом буквально. Отношение
 * горячего к холодному 7500/2000 = 3.75 - обычная величина для платины;
 * в ваттах такое соотношение смысла не имело бы.
 *
 * Цепи по схеме (проверено по списку цепей, извлечённому из исходника
 * KiCad; см. tools/ksch.py):
 *   VBAT_SENSE (ADC1) - делитель R25 12k / R26 3k на землю, то есть ровно
 *                       1/5, плюс стабилитрон D2 5.1 В как ограничитель.
 *                       Отсюда умножение на 5 ниже; предел измерения 25 В.
 *   IHEAT_SENSE (ADC2) - шунт R1 0.05 Ohm в истоке ключа Q1 (нижнее плечо
 *                       нагревателя) и разностный усилитель U1B: R10 с
 *                       шунта на инвертирующий вход, R11 100k в обратной
 *                       связи, симметричная пара R32/R33 на прямом входе.
 *                       Усиление равно R11/R10.
 *
 * Множитель 442 () - сводный коэффициент этих двух цепей. Разряд-
 * ность АЦП и опора из формулы сокращаются (обе цепи меряются одним и тем
 * же АЦП), делитель 1/5 сокращается с умножением на 5, и остаётся
 *   показание = 442 / (Rшунт * G) * R[Ом],
 * где G - усиление токового канала. Чтобы показание было в миллиомах,
 * нужно 442 / (0.05 * G) = 1000, то есть G = 8.84 ровно.
 *
 * ЗДЕСЬ РАСХОЖДЕНИЕ СО СХЕМОЙ. По номиналам перерисовки R11/R10 = 100k/10k
 * даёт G = 10, и тогда показания были бы занижены на 11.6 % (уставка 7500
 * отвечала бы настоящим 8.48 Ohm, а не 7.5 Ohm). Между тем единицы подтверждены
 * независимо - паспортом Bosch и опубликованной таблицей порогов, - поэтому
 * вероятнее ошибка в перерисовке номинала. Ближайший стандартный номинал,
 * дающий нужное: R10 = 11.3 кОм (ряд E96), тогда G = 8.850 против требуемых
 * 8.840, отклонение 0.11 %. Проверяется прозвонкой R10 и R32 на плате: они
 * должны быть равны друг другу и, по расчёту, равны 11.3 кОм, а не 10 кОм.
 */
#include "lc1.h"

/*
 * Возврат - код ошибки, 0 если всё в порядке:
 *   9 - напряжение питания ниже минимума для этого типа датчика;
 *   2 - нет тока нагревателя (< 10 отсчётов) либо Rheat > 30 Ohm (обрыв);
 *   1 - Rheat ниже минимума (замыкание нагревателя).
 */
uint8_t heater_resistance_step(void)
{
    int16_t vbat;
    int32_t rheat;

    /* Напряжение питания: отсчёт x 5 (делитель 1/5). */
    vbat          = (int16_t)((int16_t)g_vbat_raw * 5);
    g_vbat_scaled = vbat;

    if (vbat < (int16_t)g_vbat_min_raw)
        return ERR_VBAT_LOW;

    if ((int16_t)g_iheat_raw < 10) {
        g_rheat_mohm = 0;
        return ERR_NO_HEAT_CURR;
    }

    /*
     * Rheat[мОм] = vbat * 442 / iheat
     * (__mulsi3 с 0x01BA, затем __divmodsi4)
     */
    rheat        = ((int32_t)vbat * 442) / (int32_t)(int16_t)g_iheat_raw;
    g_rheat_mohm = rheat;

    if (rheat < (int32_t)(int16_t)g_rheat_min_mohm)
        return ERR_RHEAT_LOW;

    if (rheat >= 30001)
        return ERR_NO_HEAT_CURR;

    g_rheat_acc += rheat;
    g_rheat_cnt++;

    if (g_rheat_cnt != 4)
        return ERR_NONE;

    g_rheat_avg_mohm = g_rheat_acc / 4;
    g_rheat_cnt      = 0;
    g_rheat_acc      = 0;

    return ERR_NONE;
}
