/*
 * dac.c: вывод результата в двухканальный ЦАП AD5312 по SPI.
 *
 * Посылка - 16 бит, двумя байтами: старший отправляется здесь, младший
 * досылает обработчик SPI_STC.
 *
 * Формат входного сдвигового регистра (даташит AD5302/AD5312/AD5322 Rev. D,
 * стр. 15, Table 6 и рис. 31):
 *   D15 A/B  0 = канал A, 1 = канал B
 *   D14 BUF  0 = опорное напряжение небуферизовано
 *   D13 PD1 \ режим работы, Table 7 (стр. 16):
 *   D12 PD0 /   00 нормальный, 01 выкл. + 1 кОм на GND,
 *               10 выкл. + 100 кОм на GND, 11 выкл. + высокоимпедансный выход
 *   D11..D0  данные, старший бит первым
 *
 * ВАЖНО: AD5312 - 10-разрядный. Данные в нём занимают D11..D2, два младших
 * бита игнорируются (12 бит использует только AD5322). Прошивка при этом
 * везде оперирует 12-битной шкалой 0..4095, то есть фактическое разрешение
 * выхода - 10 бит. При VREF = 5 В умолчание 819 даёт ровно 0.9998 В, что
 * подтверждает и шкалу, и опору.
 */
#include "lc1.h"

void dac_write(int16_t value, uint8_t channel_b)
{
    uint8_t hi, lo;

    /*
     * Ожидание освобождения SPI
     * Пустой цикл по g_spi_state, снимаемому обработчиком SPI_STC.
     */
    while (g_spi_state != 0)
        ;

    lo = (uint8_t)value;
    hi = (uint8_t)(value >> 8);

    if ((int8_t)hi < 0) {
        /*
         * PD1 = PD0 = 1. По Table 7 даташита это "Power-Down (High
         * Impedance Output)" - канал выключается, выход переводится в
         * третье состояние. Младшие 12 бит при этом не важны, поэтому
         * магнитуда исходного значения теряется.
         *
         * Так прошивка гасит аналоговые выходы на время прогрева и при
         * ошибке: поля out_warmup/out_error в настройках по умолчанию
         * отрицательные (0x8170 и 0x84B4, см. analog_out.c).
         */
        lo = 0x00;
        hi = 0x30;
    } else {
        /* небуферизованная опора и нормальный режим работы. */
        hi &= 0x0F;
    }

    if (channel_b != 0)
        hi |= 0x80;

    g_dac_lsb   = lo;
    g_spi_state = 1;

    PORTB &= ~(1 << P_ADC_SYNC_N);
    SPSR = 0x01;
    SPCR = 0xD4; /* CPOL=0, SPR=00 -> f = fosc/2 = 8 МГц */
    SPDR = hi;
}

/*
 * ISR(SPI_STC_vect)
 *
 * Автомат на g_spi_state:
 *   1 -> ушёл старший байт, отправить младший, перейти в 2;
 *   2 -> ушёл младший байт, поднять /SYNC (защёлка в ЦАП), запретить
 *       прерывание SPI и вернуться в состояние "свободно";
 *   иное -> ничего.
 */
ISR(SPI_STC_vect)
{
    if (g_spi_state == 1) {
        SPDR = g_dac_lsb;
        g_spi_state++;
    } else if (g_spi_state == 2) {
        PORTB |= (1 << P_ADC_SYNC_N);
        SPCR        = 0x14;
        g_spi_state = 0;
    }
}
