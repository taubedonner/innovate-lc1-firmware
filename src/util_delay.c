/* util_delay.c: программные задержки. */
#include "lc1.h"

/*
 * ВНИМАНИЕ: Ghidra пометила её FID-сигнатурой `_delay_loop_2`, но это НЕ
 * стандартная функция avr-libc. В теле цикла шесть NOP:
 *
 * Итого 10 тактов на итерацию -> при 16 МГц шаг = 0.625 мкс.
 * Типовые вызовы: (2) = 1.25 мкс, (5) = 3.125 мкс, (10) = 6.25 мкс.
 */
void delay_loop_10cyc(uint16_t n)
{
    __asm__ __volatile__("        sbiw %A0, 0      \n\t"
                         "        breq 2f          \n\t"
                         "1:      nop              \n\t"
                         "        nop              \n\t"
                         "        nop              \n\t"
                         "        nop              \n\t"
                         "        nop              \n\t"
                         "        nop              \n\t"
                         "        sbiw %A0, 1      \n\t"
                         "        brne 1b          \n\t"
                         "2:                       \n\t"
                         : "+w"(n));
}

/*
 * Шаг счётчика ~ 498.75 мкс (798 итераций x 10 тактов / 16 МГц), т.е.
 * фактически это задержка в "полумиллисекундах", а не в мс - имя
 * оставлено по смыслу вызовов (delay_ms(0xc8) в fatal_halt ~ 100 мс).
 */
void delay_ms(uint16_t n)
{
    while (n > 10) {
        delay_loop_10cyc(7980);
        n -= 10;
    }
    while (n != 0) {
        delay_loop_10cyc(798);
        n--;
    }
}
